//! The installer's nonsecret catalogue, generated from validated publications.
//! The types and their validator live in `ilex-installer-model`, shared with
//! the installer that reads the table; this module only builds it.

use crate::config;
use anyhow::{Context, Result, bail};
pub use ilex_installer_model::catalogue::{
    Composition, Machine, Profile, REPOSITORY, Shell, Table, validate_tag,
};
use std::{collections::BTreeMap, path::Path};

pub const BOOT_MENU: &str = "# Generated by cargo ilexctl iso.\nlabel: \"ilex-installer\"\ngrub2:\n  timeout: 10\n  entries:\n    - name: \"Install ilex\"\n      linux: ${kernelpath} ${root} inst.graphical inst.nosave=all_ks\n      initrd: ${initrdpath}\n";

pub fn table(root: &Path, testing_tag: Option<&str>) -> Result<Table> {
    if let Some(tag) = testing_tag {
        if ["CI", "GITHUB_ACTIONS"]
            .iter()
            .any(|key| std::env::var_os(key).is_some())
        {
            bail!("--testing-tag is forbidden when CI or GITHUB_ACTIONS is set");
        }
        validate_tag(tag)?;
    }
    let rows = config::publications(root)?;
    let default = config::installer(root)?;
    let default_shells = &rows
        .iter()
        .find(|row| row.tag == default)
        .context("installer publication missing")?
        .shells;
    // One ISO per shell edition: this Anaconda network installer is the edition
    // of the installer composition's shell list (GNOME), so it offers that list
    // with every machine and no other shell list. Another shell's compositions
    // (KDE) arrive with that shell's own installer and release; offering them
    // here would also make this release wait for tags it cannot install.
    let mut compositions: Vec<_> = rows
        .iter()
        .filter(|row| !row.shells.is_empty() && &row.shells == default_shells)
        .collect();
    compositions.sort_by_key(|row| {
        if row.tag == default {
            (0, 0, String::new())
        } else {
            (1, 0, row.machine.clone())
        }
    });
    let mut table = Table {
        schema: 1,
        repository: REPOSITORY.into(),
        default,
        testing_tag: testing_tag.map(str::to_string),
        machines: BTreeMap::new(),
        shells: BTreeMap::new(),
        compositions: vec![],
        // The Linux ISO builder supplies the projection from the strict
        // image profile validator. Native tooling needs only composition rows.
        profiles: BTreeMap::new(),
        security_capabilities: BTreeMap::new(),
    };
    for row in compositions {
        if row.machine == "vm" {
            bail!("vm is never offered by the hardware installer");
        }
        table.machines.insert(
            row.machine.clone(),
            Machine {
                description: row.description.clone(),
                matches: row.matches.clone(),
            },
        );
        for (name, description) in &row.shell_descriptions {
            table.shells.insert(
                name.clone(),
                Shell {
                    label: name.clone(),
                    description: description.clone(),
                },
            );
        }
        table.compositions.push(Composition {
            tag: row.tag.clone(),
            machine: row.machine.clone(),
            shells: row.shells.clone(),
        });
    }
    Ok(table)
}
