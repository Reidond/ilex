//! The installer's nonsecret catalogue, generated from validated publications.

use crate::config::{self, DmiMatch};
use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use std::{collections::BTreeMap, path::Path};

pub const REPOSITORY: &str = "ghcr.io/reidond/ilex";
pub const BOOT_MENU: &str = "# Generated by cargo xtask iso.\nlabel: \"ilex-installer\"\ngrub2:\n  timeout: 10\n  entries:\n    - name: \"Install ilex\"\n      linux: ${kernelpath} ${root} inst.graphical inst.nosave=all_ks\n      initrd: ${initrdpath}\n";

#[derive(Debug, Serialize, Deserialize)]
pub struct Machine {
    pub description: String,
    #[serde(rename = "match")]
    pub matches: Vec<DmiMatch>,
}
#[derive(Debug, Serialize, Deserialize)]
pub struct Shell {
    pub label: String,
    pub description: String,
}
#[derive(Debug, Serialize, Deserialize)]
pub struct Composition {
    pub tag: String,
    pub machine: String,
    pub shells: Vec<String>,
}
#[derive(Debug, Serialize, Deserialize)]
pub struct Table {
    pub schema: u32,
    pub repository: String,
    pub default: String,
    #[serde(rename = "testing-tag")]
    pub testing_tag: Option<String>,
    pub machines: BTreeMap<String, Machine>,
    pub shells: BTreeMap<String, Shell>,
    pub compositions: Vec<Composition>,
    // Reserved catalogues, populated by the later profiles/security work.
    pub profiles: BTreeMap<String, serde_json::Value>,
    #[serde(rename = "security-capabilities")]
    pub security_capabilities: BTreeMap<String, serde_json::Value>,
}

pub fn validate_tag(tag: &str) -> Result<()> {
    let mut bytes = tag.bytes();
    if tag.len() > 128
        || !bytes
            .next()
            .is_some_and(|b| b.is_ascii_alphanumeric() || b == b'_')
        || !bytes.all(|b| b.is_ascii_alphanumeric() || b"_.-".contains(&b))
    {
        bail!("invalid image tag {tag:?}: expected [A-Za-z0-9_][A-Za-z0-9_.-]{{0,127}}");
    }
    Ok(())
}

pub fn table(root: &Path, testing_tag: Option<&str>) -> Result<Table> {
    if let Some(tag) = testing_tag {
        if ["CI", "GITHUB_ACTIONS"]
            .iter()
            .any(|key| std::env::var_os(key).is_some())
        {
            bail!("--testing-tag is forbidden when CI or GITHUB_ACTIONS is set");
        }
        validate_tag(tag)?;
    }
    let rows = config::publications(root)?;
    let manifest = config::manifest(&root.join("image.toml"))?;
    let shell_order = manifest["publish"]
        .as_array()
        .context("publish must be an array")?
        .iter()
        .map(|entry| {
            config::string_list(
                entry.as_table().context("publish entry must be a table")?,
                "shells",
            )
        })
        .collect::<Result<Vec<_>>>()?;
    let default = config::installer(root)?;
    let default_shells = &rows
        .iter()
        .find(|row| row.tag == default)
        .context("installer publication missing")?
        .shells;
    let mut compositions: Vec<_> = rows.iter().filter(|row| !row.shells.is_empty()).collect();
    compositions.sort_by_key(|row| {
        if row.tag == default {
            (0, 0, String::new())
        } else if &row.shells == default_shells {
            (1, 0, row.machine.clone())
        } else {
            (
                2,
                shell_order
                    .iter()
                    .position(|shells| shells == &row.shells)
                    .unwrap_or(usize::MAX),
                String::new(),
            )
        }
    });
    let mut table = Table {
        schema: 1,
        repository: REPOSITORY.into(),
        default,
        testing_tag: testing_tag.map(str::to_string),
        machines: BTreeMap::new(),
        shells: BTreeMap::new(),
        compositions: vec![],
        profiles: BTreeMap::new(),
        security_capabilities: BTreeMap::new(),
    };
    for row in compositions {
        if row.machine == "vm" {
            bail!("vm is never offered by the hardware installer");
        }
        table.machines.insert(
            row.machine.clone(),
            Machine {
                description: row.description.clone(),
                matches: row.matches.clone(),
            },
        );
        for (name, description) in &row.shell_descriptions {
            table.shells.insert(
                name.clone(),
                Shell {
                    label: name.clone(),
                    description: description.clone(),
                },
            );
        }
        table.compositions.push(Composition {
            tag: row.tag.clone(),
            machine: row.machine.clone(),
            shells: row.shells.clone(),
        });
    }
    Ok(table)
}
