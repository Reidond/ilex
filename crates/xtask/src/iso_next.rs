//! `cargo ilexctl iso --next`: build the live installer ISO of the next
//! installer, one edition at a time.
//!
//! No Anaconda, Cockpit or Firefox: `installer/next/Containerfile` is
//! fedora-bootc plus one edition's compositor and interface, and the same
//! `image-builder … generic-iso` path as the network installer (`iso`) turns it
//! into a live ISO. The ISO is written to `<state dir>/iso-next` with its
//! checksum and a list of its largest packages, and it is never released:
//! CI keeps it as a workflow artifact on request.
//!
//! The edition identifier (`gnome`) names the image stage, its files below
//! `installer/next/editions/` and the ISO. What a person reads as its name is
//! `installer/next/editions.toml`'s `display-name`, the only place it lives;
//! the build writes it into the image as `edition.json`.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use ilex_devkit::{Workspace, cmd};

use crate::iso::{copy_sources, find_iso, run_image_builder, sha256_file};

/// The edition built when none is named.
pub const DEFAULT_EDITION: &str = "gnome";
/// The Network installer's ISO has to stay under GitHub's limit for a release
/// asset; the next one is held to the same budget.
const ISO_LIMIT: u64 = 2 << 30;
/// What the Anaconda network installer's ISO measured (2026-11-16), to compare.
const ANACONDA_ISO: u64 = 1_953_595_392;
/// Boot menu: label of the volume (at most 32 bytes in ISO 9660) and the two
/// entries the plan sets. The second leaves the display to the firmware's
/// framebuffer; the session then draws on the CPU (`GSK_RENDERER=cairo`).
const MENU: &str = "# Generated by cargo ilexctl iso --next.\nlabel: \"ilex-installer-{edition}\"\ngrub2:\n  timeout: 10\n  entries:\n    - name: \"Install ilex\"\n      linux: ${kernelpath} ${root} quiet\n      initrd: ${initrdpath}\n    - name: \"Install ilex (basic graphics)\"\n      linux: ${kernelpath} ${root} quiet nomodeset\n      initrd: ${initrdpath}\n";

pub struct Build<'a> {
    pub edition: &'a str,
    /// Where the ISO goes (default `<state dir>/iso-next`).
    pub output_dir: Option<&'a Path>,
}

/// One edition as `editions.toml` declares it.
struct Edition {
    id: String,
    display_name: String,
}

/// Does this `ilexctl test` filter select the next installer's `iso::next…`
/// trials (which boot its ISO) rather than the Anaconda installer's `iso::`?
pub fn is_next_filter(filter: &str) -> bool {
    filter.contains("iso::next")
}

/// Why the remote (native Windows) path refuses `iso --next` and `test
/// iso::next`: the builder collects only `<state dir>/iso` (the Anaconda ISO)
/// and stages only `ILEX_ISO`, while the next installer writes
/// `<state dir>/iso-next` and the trials read `ILEX_ISO_NEXT`. Run them on a
/// Linux host.
pub const REMOTE_UNSUPPORTED: &str = "the next installer's live ISO (`iso --next`, `test iso::next`) is not supported from native Windows yet: the builder returns only the Anaconda installer's ISO directory, so its ISO would never reach this machine and `ILEX_ISO_NEXT` is never staged. Run it on a Linux host";

/// File name of the ISO of an edition.
pub fn iso_name(edition: &str) -> String {
    format!("ilex-installer-{edition}")
}

fn edition(root: &Path, id: &str) -> Result<Edition> {
    let valid = id.starts_with(|c: char| c.is_ascii_lowercase())
        && id.len() <= 16
        && id
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    if !valid {
        bail!("invalid edition {id:?}: expected [a-z][a-z0-9-]{{0,15}}");
    }
    let table = ilex_devkit::config::manifest(&root.join("installer/next/editions.toml"))?;
    let known: Vec<&String> = table.keys().collect();
    let entry = table.get(id).and_then(|e| e.as_table()).with_context(|| {
        format!("unknown edition {id:?}; installer/next/editions.toml has {known:?}")
    })?;
    for key in entry.keys() {
        if key != "display-name" {
            bail!("installer/next/editions.toml [{id}]: unknown key {key:?}");
        }
    }
    let display_name = entry
        .get("display-name")
        .and_then(|v| v.as_str())
        .with_context(|| format!("installer/next/editions.toml [{id}] needs a display-name"))?;
    if display_name.trim() != display_name
        || display_name.is_empty()
        || display_name.len() > 64
        || display_name.chars().any(char::is_control)
    {
        bail!(
            "installer/next/editions.toml [{id}]: display-name must be 1-64 characters, trimmed, without control characters"
        );
    }
    if !root.join("installer/next/editions").join(id).is_dir() {
        bail!("edition {id}: installer/next/editions/{id}/ is missing");
    }
    Ok(Edition {
        id: id.into(),
        display_name: display_name.into(),
    })
}

/// The edition record the interface reads from the live image.
fn edition_json(edition: &Edition) -> Result<Vec<u8>> {
    let mut bytes = serde_json::to_vec_pretty(&serde_json::json!({
        "schema": 1,
        "edition": edition.id,
        "display-name": edition.display_name,
    }))?;
    bytes.push(b'\n');
    Ok(bytes)
}

/// Build the live image and the ISO and return the ISO's path; its checksum
/// and package sizes are written next to it.
pub fn build(ws: &Workspace, spec: &Build) -> Result<PathBuf> {
    ws.ensure_state()?;
    let edition = edition(&ws.root, spec.edition)?;
    let out_dir = spec
        .output_dir
        .map_or_else(|| ws.state_dir().join("iso-next"), Path::to_path_buf);
    ilex_devkit::ownership::ensure_directory(&out_dir, &ws.identity()?)?;
    let out_dir = std::path::absolute(&out_dir)?;

    // The builder stage compiles the interface from this snapshot of the
    // workspace; stale copies of removed crates must not survive.
    let generated = out_dir.join("generated");
    fs::create_dir_all(&generated)?;
    fs::write(generated.join("edition.json"), edition_json(&edition)?)?;
    fs::write(
        generated.join("iso.yaml"),
        MENU.replace("{edition}", &edition.id),
    )?;
    for file in ["Cargo.toml", "Cargo.lock"] {
        fs::copy(ws.root.join(file), generated.join(file))?;
    }
    let crates = generated.join("crates");
    if crates.exists() {
        fs::remove_dir_all(&crates)?;
    }
    copy_sources(&ws.root.join("crates"), &crates)?;

    let image = format!("localhost/ilex-installer-next:{}.{}", ws.slug, edition.id);
    let transaction = ilex_devkit::ownership::ImageTransaction::new(ws, &image)?;
    let (identity, source) = ws.source_identity()?;
    let context = ws.root.join("installer/next");
    cmd::run(
        Command::new("podman")
            // Host networking: in CI this runs podman inside a container,
            // where the nested bridge network has no DNS.
            .args(["build", "--network=host", "--file"])
            .arg(context.join("Containerfile"))
            .args([
                "--build-context",
                &format!("generated={}", generated.display()),
            ])
            .args(["--build-arg", &format!("EDITION={}", edition.id)])
            .args(["--tag", transaction.temporary()])
            .args([
                "--label",
                &format!("ilex.checkout-owner={}", identity.owner),
            ])
            .arg(&context),
    )?;
    anyhow::ensure!(
        ws.source_identity()?.1.digest == source.digest,
        "source changed during the installer build; refusing promotion"
    );
    transaction.promote(ws)?;

    let build_dir = out_dir.join("build");
    if build_dir.exists() {
        fs::remove_dir_all(&build_dir)?;
    }
    fs::create_dir_all(&build_dir)?;
    run_image_builder(ws, &image, &build_dir, &iso_name(&edition.id))?;

    let built = find_iso(&build_dir)?;
    let iso = out_dir.join(format!("{}.iso", iso_name(&edition.id)));
    if built != iso {
        fs::rename(&built, &iso).with_context(|| format!("moving {}", built.display()))?;
    }
    let size = fs::metadata(&iso)?.len();
    let sha256 = sha256_file(&iso)?;
    fs::write(
        out_dir.join(format!("{}.iso.sha256", iso_name(&edition.id))),
        format!("{sha256}  {}.iso\n", iso_name(&edition.id)),
    )?;
    if let Err(error) = largest_packages(&image, &out_dir.join("largest-packages.txt")) {
        eprintln!("ilexctl: could not list the largest packages: {error:#}");
    }
    let gib = |bytes: u64| bytes as f64 / (1u64 << 30) as f64;
    eprintln!(
        "built {} ({:.2} GiB, {:+.0} MiB against the Anaconda network installer's {:.2} GiB, limit {:.0} GiB; sha256 {sha256})",
        iso.display(),
        gib(size),
        (size as f64 - ANACONDA_ISO as f64) / (1u64 << 20) as f64,
        gib(ANACONDA_ISO),
        gib(ISO_LIMIT),
    );
    if size >= ISO_LIMIT {
        bail!(
            "the ISO is {:.2} GiB; a GitHub release asset has to be under 2 GiB",
            gib(size)
        );
    }
    Ok(iso)
}

/// The ten largest installed packages of the live image, for reports.
fn largest_packages(image: &str, to: &Path) -> Result<()> {
    let listing = cmd::output(Command::new("podman").args([
        "run",
        "--rm",
        "--network=none",
        image,
        "rpm",
        "-qa",
        "--queryformat",
        "%{SIZE} %{NAME}-%{VERSION}-%{RELEASE}\\n",
    ]))?;
    let mut sizes: Vec<(u64, &str)> = listing
        .lines()
        .filter_map(|line| {
            let (size, name) = line.split_once(' ')?;
            Some((size.parse().ok()?, name))
        })
        .collect();
    sizes.sort_by(|a, b| b.cmp(a));
    let mut text = String::new();
    for (size, name) in sizes.iter().take(10) {
        text.push_str(&format!(
            "{:>9.1} MiB  {name}\n",
            *size as f64 / (1u64 << 20) as f64
        ));
    }
    text.push_str(&format!(
        "{} packages, {:.0} MiB installed\n",
        sizes.len(),
        sizes.iter().map(|(s, _)| *s).sum::<u64>() as f64 / (1u64 << 20) as f64
    ));
    fs::write(to, text)?;
    Ok(())
}
